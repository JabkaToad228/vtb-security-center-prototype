/**
 * «Запись звонка»: расшифровки звонков мошенников клиентам банка.
 * Это реконструкции по типичным схемам 2025–2026 годов из предупреждений ВТБ и Банка России,
 * а не записи настоящих разговоров: имена, суммы и детали вымышлены.
 * Чтобы вставить настоящую обезличенную расшифровку, достаточно заменить `lines`.
 */
export type RecordLine = {
  at: string
  who: 'caller' | 'client'
  /** Кто звонит на этом этапе — в многоэтапных схемах их несколько. */
  role?: string
  text: string
  /** Приём манипуляции. Первая реплика с флагом — момент, когда пора класть трубку. */
  flag?: string
}

export type CallRecording = {
  id: string
  title: string
  client: string
  duration: string
  lines: RecordLine[]
  /** Чем закончился разговор в этой истории. */
  ending: string
  /** Где вмешался бы Центр безопасности. */
  withUs: string[]
}

