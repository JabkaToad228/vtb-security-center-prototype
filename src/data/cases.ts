export const caseById = (id: string) => cases.find((c) => c.id === id)

export const casesFor = (owner: CaseOwner) => cases.filter((c) => c.owner === owner)

const rub = (n: number) => `${new Intl.NumberFormat('ru-RU').format(n)} ₽`

/** Итог «Истории защиты» считается из самих кейсов, чтобы цифры не расходились со списком. */
export const historyStats = {
  prevented: cases.length,
  saved: rub(cases.reduce((sum, c) => sum + c.saved, 0)),
}
