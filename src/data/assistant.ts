const rules: { topic: AssistantTopic; re: RegExp }[] = [
  { topic: 'money', re: /(перев[её]л|перевела|отправил|отправила|украли|списали|списал|потерял)/ },
  { topic: 'sms', re: /(код|смс|sms|пароль|парол)/ },
  { topic: 'link', re: /(ссылк|сайт|домен|фишинг)/ },
  { topic: 'relatives', re: /(мам|пап|родител|бабуш|дедуш|близк|сестр|брат)/ },
  { topic: 'call', re: /(звон|позвон|служб|банк|полиц|следовател|безопасн)/ },
]

export function detectTopic(text: string): AssistantTopic | 'hello' | null {
  const t = text.toLowerCase()
  if (/^(привет|здравств|добрый)/.test(t)) return 'hello'
  return rules.find((r) => r.re.test(t))?.topic ?? null
}
